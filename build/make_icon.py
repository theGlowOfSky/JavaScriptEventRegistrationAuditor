"""Generates the plugin icon (SVG, PNG, ICO) and the Base64 resource class from one geometry definition."""
import base64, io, os
from PIL import Image, ImageDraw
import sys

# The project now uses the supplied icon files in assets/. Running this script would overwrite them with the
# original generated icon, so it only runs when explicitly forced.
if "--force" not in sys.argv:
    print("make_icon.py is disabled: assets/ contains the supplied icons. Use --force to regenerate the original icon.")
    sys.exit(1)

BLUE, TEAL, WHITE = "#0F6CBD", "#00B7C3", "#FFFFFF"

def quad(p0, c, p1, n=18):
    return [((1-t)**2*p0[0]+2*(1-t)*t*c[0]+t*t*p1[0], (1-t)**2*p0[1]+2*(1-t)*t*c[1]+t*t*p1[1]) for t in [i/n for i in range(n+1)]]

def brace(x0, x1, y0, y1, left=True):
    xm = (x0+x1)/2; ym=(y0+y1)/2; h=y1-y0
    a, b = (x1, x0) if left else (x0, x1)
    pts = quad((a,y0),(xm,y0),(xm,y0+.16*h))
    pts += [(xm,y0+.16*h),(xm,ym-.16*h)]
    pts += quad((xm,ym-.16*h),(xm,ym),(b,ym))
    pts += quad((b,ym),(xm,ym),(xm,ym+.16*h))
    pts += [(xm,ym+.16*h),(xm,y1-.16*h)]
    pts += quad((xm,y1-.16*h),(xm,y1),(a,y1))
    return pts

LB = brace(44, 92, 52, 168, True)
RB = brace(164, 212, 52, 168, False)
BARS = [(104,84,152,84),(104,110,152,110),(104,136,152,136)]
BADGE = (186,186,46)
CHECK = [(166,186),(181,201),(208,171)]

def poly(pts): return " ".join(f"{x:.1f},{y:.1f}" for x,y in pts)

svg = f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 256" width="256" height="256">
  <title>JavaScript Event Registration Auditor</title>
  <rect x="8" y="8" width="240" height="240" rx="40" fill="{BLUE}"/>
  <g fill="none" stroke="{WHITE}" stroke-width="12" stroke-linecap="round" stroke-linejoin="round">
    <polyline points="{poly(LB)}"/><polyline points="{poly(RB)}"/>
''' + "".join(f'    <line x1="{a}" y1="{b}" x2="{c}" y2="{d}" stroke-width="10"/>\n' for a,b,c,d in BARS) + f'''  </g>
  <circle cx="{BADGE[0]}" cy="{BADGE[1]}" r="{BADGE[2]+8}" fill="{BLUE}"/>
  <circle cx="{BADGE[0]}" cy="{BADGE[1]}" r="{BADGE[2]}" fill="{TEAL}"/>
  <polyline points="{poly(CHECK)}" fill="none" stroke="{WHITE}" stroke-width="12" stroke-linecap="round" stroke-linejoin="round"/>
</svg>
'''

def render(size=1024):
    k = size/256.0
    im = Image.new("RGBA", (size,size), (0,0,0,0)); d = ImageDraw.Draw(im)
    S = lambda pts: [(x*k,y*k) for x,y in pts]
    d.rounded_rectangle([8*k,8*k,248*k,248*k], radius=40*k, fill=BLUE)
    def stroke(pts, w, col=WHITE):
        pts = S(pts); d.line(pts, fill=col, width=int(w*k), joint="curve")
        r = w*k/2
        for x,y in (pts[0], pts[-1]): d.ellipse([x-r,y-r,x+r,y+r], fill=col)
    stroke(LB,12); stroke(RB,12)
    for a,b,c,e in BARS: stroke([(a,b),(c,e)],10)
    bx,by,br = BADGE
    d.ellipse([(bx-br-8)*k,(by-br-8)*k,(bx+br+8)*k,(by+br+8)*k], fill=BLUE)
    d.ellipse([(bx-br)*k,(by-br)*k,(bx+br)*k,(by+br)*k], fill=TEAL)
    stroke(CHECK,12)
    return im

big = render(1024)
def sized(n): return big.resize((n,n), Image.LANCZOS)

os.makedirs("assets", exist_ok=True)
open("assets/icon.svg","w",encoding="utf-8").write(svg)
sized(512).save("assets/icon-512.png")
sized(256).save("assets/icon-256.png")
sized(32).save("assets/icon-32.png")
sized(80).save("assets/icon-80.png")
sized(256).save("assets/icon.ico", sizes=[(16,16),(24,24),(32,32),(48,48),(64,64),(128,128),(256,256)])

def b64(n):
    buf = io.BytesIO(); sized(n).save(buf, "PNG"); return base64.b64encode(buf.getvalue()).decode()

cs = f'''// <auto-generated> by build/make_icon.py - do not edit by hand. </auto-generated>
namespace JavaScriptEventRegistrationAuditor.Resources
{{
    /// <summary>Base64 PNG icons used by the XrmToolBox plugin tile metadata (must be compile-time constants).</summary>
    public static class IconData
    {{
        public const string Small32 = "{b64(32)}";
        public const string Big80 = "{b64(80)}";
    }}
}}
'''
open("src/JavaScriptEventRegistrationAuditor/Resources/IconData.cs","w",encoding="utf-8").write(cs)
